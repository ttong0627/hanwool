def build() -> Path:
    wb = Workbook()
    ws = wb.active
    ws.title = "테스트명단35"

    header_fill = PatternFill("solid", fgColor="2563EB")
    header_font = Font(color="FFFFFF", bold=True, size=11)
    center = Alignment(horizontal="center", vertical="center")

    ws.append(HEADERS)
    for col, _ in enumerate(HEADERS, start=1):
        cell = ws.cell(row=1, column=col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = center

    for idx, (name, dong, addr, detail, items, code, qty, req) in enumerate(ROWS, start=1):
        phone = f"010-7700-{idx:04d}"  # 테스트용 가상번호 (실제 발송은 테스트폰으로 리다이렉트됨)
        ws.append([name, phone, dong, addr, detail, items, code, qty, req])

    widths = [10, 16, 10, 34, 20, 16, 8, 8, 18]
    for col, w in enumerate(widths, start=1):
        ws.column_dimensions[chr(64 + col)].width = w

    out = Path(__file__).parent / "gwangju_18dong_test_orders_35.xlsx"
    wb.save(out)
    return out


